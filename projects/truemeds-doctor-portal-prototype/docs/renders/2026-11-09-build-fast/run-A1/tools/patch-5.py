"""Build aid (run A1): compare-step1.mjs gets a report mode for later steps (brief D-95: run once per run, as a report). One-off patch."""
import os
PRJ = os.path.normpath(os.path.join(os.path.dirname(__file__), "../../../../.."))
p = os.path.join(PRJ, "tests/compare-step1.mjs"); s = open(p).read()
old = 'const ids = window.TM_STATE_MAP.pictures.filter((r) => r.step === 1).map((r) => r.id).filter((id) => !FLT || FLT.test(id));'
new = '''// STEPS=2-4 (build-fast brief, D-95): report mode for the later steps — no per-state gate. Every picture of those steps is captured
// from the built app and its changed area (share of the picture, spinner boxes masked) is reported; states over 1 % are listed
// with their side-by-side sheet. Exit 0: the report is read, not enforced.
const STEPS = process.env.STEPS ? process.env.STEPS.split("-").map(Number) : null;
const ids = window.TM_STATE_MAP.pictures.filter((r) => (STEPS ? r.step >= STEPS[0] && r.step <= (STEPS[1] || STEPS[0]) : r.step === 1)).map((r) => r.id).filter((id) => !FLT || FLT.test(id));'''
assert old in s; s = s.replace(old, new)
old2 = '// ---- run ----\nconst results = [];'
new2 = '''// ---- report mode (STEPS) ----
if (STEPS) {
  const rows = [];
  for (const id of ids) {
    const pic = window.TM_STATE_MAP.pictures.find((r) => r.id === id).picture;
    for (const w of [390, 360]) {
      const A = PNG.sync.read(fs.readFileSync(path.join(PICS, `${pic}_w${w}.png`)));
      const built = await shoot(`http://localhost:${PORT}/?capture=1&s=${id}&w=${w}`, w, { capture: true });
      const B = built.png;
      const masks = built.spin.map(([x, y, ww, hh]) => [Math.floor((x - 2) * 2), Math.floor((y - 2) * 2), Math.ceil((x + ww + 2) * 2), Math.ceil((y + hh + 2) * 2)]);
      const same = A.width === B.width && A.height === B.height;
      const { regions, total } = same ? regionsOf(A, B, masks) : { regions: [], total: A.width * A.height };
      const pct = (100 * total) / (A.width * A.height);
      const row = { id, w, changedPx: total, changedPct: Math.round(pct * 100) / 100, errors: built.errs, flagged: pct > 1 || built.errs.length > 0 };
      if (row.flagged && same) sheet(A, B, regions.map((r) => ({ ...r, why: "unexplained" })), path.join(OUT, `${id}_w${w}.png`));
      rows.push(row);
      console.log(`${row.flagged ? "OVER 1% " : "ok      "} ${id} @${w}  changed ${row.changedPct}%${built.errs.length ? "  errors: " + built.errs.join(" | ") : ""}`);
    }
  }
  await browser.close(); srv.close();
  const over = rows.filter((r) => r.flagged);
  fs.writeFileSync(path.join(OUT, "results.json"), JSON.stringify({ steps: process.env.STEPS, thresholdPerChannel: THRESH, pictures: rows.length, over1pct: over.length, rows }, null, 1));
  fs.writeFileSync(path.join(OUT, "results.md"), [`# Compare report, steps ${process.env.STEPS} — approved picture vs built app`, "",
    `Generated by \\`STEPS=${process.env.STEPS} node tests/compare-step1.mjs\\` (a pixel differs when any channel differs by more than ${THRESH}/255; spinner boxes masked). Report only (D-95): states whose changed area is over 1 % are listed with a side-by-side sheet (approved | built | heatmap).`, "",
    `Pictures ${rows.length} · over 1 %: **${over.length}**`, "", "| State | Width | Changed | Sheet |", "|---|---|---|---|",
    ...rows.map((r) => `| \\`${r.id}\\` | ${r.w} | ${r.changedPct} %${r.errors.length ? " (page errors)" : ""} | ${r.flagged ? `\\`${r.id}_w${r.w}.png\\`` : "—"} |`)].join("\\n") + "\\n");
  console.log(`\\nsteps ${process.env.STEPS}: ${rows.length} pictures, ${over.length} over 1 %`);
  process.exit(0);
}

// ---- run ----
const results = [];'''
assert old2 in s; s = s.replace(old2, new2)
open(p, "w").write(s)
print("patched")
