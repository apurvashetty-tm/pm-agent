"""Screens audit: shared facts digest from measure.json (both reviewers get it). python3 tools/facts.py <run> > facts.md"""
import sys, json, pathlib, collections
RUN = pathlib.Path(sys.argv[1]); M = json.loads((RUN / 'measure.json').read_text())
OK = {0, 4, 8, 16, 24, 32}
print('# Shared facts (generated by tools/facts.py from measure.json)\n')
print('CSS px, relative to the screen top-left. "gap" = top of a block minus the bottom of the nearest block above it in the same region (panel / bar / sheet). Icons ≤ 24 skipped.\n')
for scr, states in M.items():
    print(f'## {scr}\n')
    print('| state | size | panel top | bar top / h | content→bar | scrolls | off-scale gaps (gap: block ← above) | targets < 48 | type < 14 or interactive < 16 |')
    print('|---|---|---|---|---|---|---|---|---|')
    for st, sizes in states.items():
        for size, m in sizes.items():
            off = [f"{b['gapAbove']:g}: {b['text'][:22] or b['cls'][:22]} ← {(b['above'] or '')[:18]}" for b in m['blocks']
                   if b['gapAbove'] is not None and round(b['gapAbove']) not in OK and not (b['cls'].startswith('tm-icon') and b['w'] <= 24)]
            small = [f"{b['text'][:18] or b['cls'][:18]} {b['target']['w']}×{b['target']['h']}" for b in m['blocks'] if b.get('target') and min(b['target']['w'], b['target']['h']) < 47.5]
            tiny = [f"{b['text'][:18]} {b['font'].split()[0]}" for b in m['blocks'] if b['text'] and float(b['font'].split('px')[0]) < 14]
            sc = ', '.join(f"{s['cls'][:14]} +{s['overflow']}" for s in m['scroll']) or '—'
            bar = f"{m['barTop']} / {m['barH']}" if m['barTop'] is not None else '—'
            print(f"| {st} | {size} | {m['panelTop']} | {bar} | {m['contentToBar'] if m['contentToBar'] is not None else '—'} | {sc} | {'; '.join(off[:6]) or '—'} | {'; '.join(small[:4]) or '—'} | {'; '.join(tiny[:3]) or '—'} |")
    print()
# component inventory
print('## Component inventory (all states, both sizes)\n')
inv = collections.defaultdict(set)
for scr, states in M.items():
    for st, sizes in states.items():
        for size, m in sizes.items():
            for b in m['blocks']:
                if b.get('notice'): inv[f"notice {b['notice']} ({b['region']})"].add(f"{scr}: {b['font']} pad {b.get('pad')} r {b.get('radius')} align {b['align']} x {b['x']:g}")
                if b.get('btn'): inv[f"button {b['btn']}"].add(f"{scr} ({b['region']}): {b['target']['w']}×{b['target']['h']} {b['font']}")
print('| component | where / measured |'); print('|---|---|')
for k, v in sorted(inv.items()): print(f"| {k} | {'<br>'.join(sorted(v))} |")
